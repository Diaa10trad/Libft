#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	size_t	i;
	size_t	s_len;
	char	*dest;

	i = 0;
	if (!s || !f)
		return (NULL);
	s_len = ft_strlen(s);
	dest = malloc((s_len + 1) * sizeof(char));
	if (!dest)
		return (NULL);
	while (i < s_len)
	{
		dest[i] = f(i, s[i]);
		i++;
	}
	dest[i] = '\0';
	return (dest);
}
